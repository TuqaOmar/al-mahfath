/**
 * Normalizes Arabic text for flexible, resilient searching
 * (removes hamza variants, taa marbouta, alef maqsura, tashkeel, and quranic symbols)
 */
export const normalizeArabicText = (text) => {
  if (!text) return '';
  return text
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\u064B-\u065F\u0670]/g, '') // tashkeel
    .replace(/[\u06D6-\u06ED]/g, '') // quranic stop signs
    .replace(/\s+/g, ' ')
    .toLowerCase()
    .trim();
};

